package org.psycommunity.api.service;

import ai.djl.huggingface.tokenizers.Encoding;
import ai.djl.huggingface.tokenizers.HuggingFaceTokenizer;
import ai.onnxruntime.OnnxTensor;
import ai.onnxruntime.OrtEnvironment;
import ai.onnxruntime.OrtSession;
import jakarta.annotation.PostConstruct;
import jakarta.annotation.PreDestroy;
import org.psycommunity.api.domain.UserAccount;
import org.psycommunity.api.repository.UserAccountRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;
import org.springframework.transaction.support.TransactionTemplate;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.PreparedStatement;
import java.time.Instant;
import java.util.*;
import java.util.regex.Pattern;

@Service
public class EmotionService {
    private static final Logger log=LoggerFactory.getLogger(EmotionService.class);
    private static final String MODEL_VERSION="erlanger-onnx-8cbfb8b";
    private static final Pattern INTENSE=Pattern.compile("绝望|崩溃|撑不住|受不了了|无法忍受|痛不欲生|活不下去|不想活|伤害自己|结束生命|自杀|非常痛苦|特别痛苦");
    // Explicit crisis signals must not be gated by a general-purpose sentiment score.
    private static final Pattern CRISIS=Pattern.compile("自杀|自尽|轻生|杀死自己|杀了自己|结束自己的生命|结束生命|不想活了|不想再活|活不下去|没什么好再活|没有什么好再活|割腕|自残|割伤自己|划伤自己");
    private final JdbcTemplate db;
    private final UserAccountRepository users;
    private final TransactionTemplate transactions;
    private final boolean enabled;
    private final Path modelPath;
    private final double threshold;
    private volatile boolean available;
    private volatile String reason="尚未初始化";
    private OrtEnvironment environment;
    private OrtSession session;
    private HuggingFaceTokenizer tokenizer;

    public EmotionService(JdbcTemplate db, UserAccountRepository users, TransactionTemplate transactions,
                          @Value("${app.emotion.enabled:false}") boolean enabled,
                          @Value("${app.emotion.model-path:./models/emotion}") String modelPath,
                          @Value("${app.emotion.alert-threshold:0.80}") double threshold) {
        this.db=db; this.users=users; this.transactions=transactions; this.enabled=enabled;
        this.modelPath=Path.of(modelPath); this.threshold=Math.max(0.5,Math.min(1.0,threshold));
    }

    @PostConstruct
    void initialize() {
        db.execute("CREATE TABLE IF NOT EXISTS psy_emotion_jobs (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid VARCHAR(50) NOT NULL, source_type VARCHAR(20) NOT NULL, source_id VARCHAR(80) NOT NULL, content VARCHAR(4000), status VARCHAR(16) NOT NULL, created_at VARCHAR(40) NOT NULL, UNIQUE(source_type,source_id))");
        db.execute("CREATE TABLE IF NOT EXISTS psy_emotion_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid VARCHAR(50) NOT NULL, source_type VARCHAR(20) NOT NULL, source_id VARCHAR(80) NOT NULL, negative_score DOUBLE PRECISION NOT NULL, attention BOOLEAN NOT NULL, model_version VARCHAR(80) NOT NULL, created_at VARCHAR(40) NOT NULL, UNIQUE(source_type,source_id))");
        db.execute("ALTER TABLE psy_emotion_events ADD COLUMN IF NOT EXISTS admin_delivery_pending BOOLEAN NOT NULL DEFAULT FALSE");
        db.execute("CREATE TABLE IF NOT EXISTS psy_notifications (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recipient_uid VARCHAR(50) NOT NULL, event_id BIGINT NOT NULL, target_uid VARCHAR(50) NOT NULL, message VARCHAR(500) NOT NULL, is_read BOOLEAN NOT NULL, created_at VARCHAR(40) NOT NULL, UNIQUE(recipient_uid,event_id))");
        if(!enabled) { reason="已禁用"; log.info("本地情感模型不可用模式：已禁用；其他功能正常启动"); return; }
        try {
            Path model=modelPath.resolve("model.onnx"), tokens=modelPath.resolve("tokenizer.json");
            if(!Files.isRegularFile(model) || !Files.isRegularFile(tokens)) throw new IllegalStateException("缺少模型或分词文件");
            environment=OrtEnvironment.getEnvironment();
            try (OrtSession.SessionOptions options=new OrtSession.SessionOptions()) {
                options.setIntraOpNumThreads(1);
                session=environment.createSession(model.toAbsolutePath().toString(),options);
            }
            tokenizer=HuggingFaceTokenizer.builder().optTokenizerPath(tokens.toAbsolutePath()).optMaxLength(256).optTruncation(true).build();
            score("今天心情不错");
            db.update("UPDATE psy_emotion_jobs SET status='pending' WHERE status='processing'");
            available=true; reason="模型已加载";
            log.info("本地情感模型可用模式：已加载并通过启动检查");
        } catch (Exception | LinkageError ex) {
            available=false; reason="模型文件或运行环境不可用";
            log.warn("本地情感模型不可用，其他功能正常启动；请检查运行环境",ex);
            closeResources();
        }
    }

    public Map<String,Object> status() { return Map.of("enabled",enabled,"available",available,"mode",available?"available":"unavailable","message",reason); }

    public void submit(String uid,String source,Object sourceId,String content) {
        if(!available || content==null || content.isBlank()) return;
        try {
            db.update("INSERT INTO psy_emotion_jobs(uid,source_type,source_id,content,status,created_at) VALUES (?,?,?,?,?,?)",
                    uid,source,String.valueOf(sourceId),content.substring(0,Math.min(content.length(),4000)),"pending",Instant.now().toString());
        } catch (Exception ex) {
            log.error("无法记录情绪分析任务，来源 {}；原操作不受影响",source,ex);
        }
    }

    @Scheduled(fixedDelayString="${EMOTION_POLL_INTERVAL_MS:2000}")
    public void processPending() {
        if(!available) return;
        List<Map<String,Object>> jobs=db.queryForList("SELECT * FROM psy_emotion_jobs WHERE status='pending' ORDER BY id LIMIT 10");
        for(Map<String,Object> job:jobs) {
            long id=((Number)job.get("id")).longValue();
            if(db.update("UPDATE psy_emotion_jobs SET status='processing' WHERE id=? AND status='pending'",id)!=1) continue;
            try {
                String content=Objects.toString(job.get("content"),"");
                double maxScore=0; boolean attention=CRISIS.matcher(content).find();
                int[] points=content.codePoints().toArray();
                for(int start=0; start<points.length; start+=150) {
                    String part=new String(points,start,Math.min(180,points.length-start));
                    double negative=score(part);
                    maxScore=Math.max(maxScore,negative);
                    if(negative>=threshold && INTENSE.matcher(part).find()) attention=true;
                    if(start+180>=points.length) break;
                }
                final double observed=maxScore; final boolean notify=attention;
                transactions.executeWithoutResult(status -> persist(job,id,observed,notify));
            } catch (Exception | LinkageError ex) {
                db.update("UPDATE psy_emotion_jobs SET status='pending' WHERE id=?",id);
                available=false; reason="模型运行失败，等待管理员检查";
                log.error("情绪分析执行失败，已进入不可用模式；待处理任务会保留",ex);
                return;
            }
        }
    }

    private synchronized double score(String text) throws Exception {
        Encoding encoding=tokenizer.encode(text);
        try(OnnxTensor ids=OnnxTensor.createTensor(environment,new long[][]{encoding.getIds()});
            OnnxTensor mask=OnnxTensor.createTensor(environment,new long[][]{encoding.getAttentionMask()});
            OnnxTensor types=OnnxTensor.createTensor(environment,new long[][]{encoding.getTypeIds()})) {
            Map<String,OnnxTensor> inputs=new HashMap<>();
            for(String name:session.getInputNames()) {
                switch(name) {
                    case "input_ids" -> inputs.put(name,ids);
                    case "attention_mask" -> inputs.put(name,mask);
                    case "token_type_ids" -> inputs.put(name,types);
                    default -> throw new IllegalStateException("不支持的模型输入: "+name);
                }
            }
            try(OrtSession.Result result=session.run(inputs)) {
                Object output=result.get(0).getValue();
                if(!(output instanceof float[][] logits) || logits.length==0 || logits[0].length<2) throw new IllegalStateException("模型输出格式不正确");
                double a=logits[0][0], b=logits[0][1], m=Math.max(a,b);
                return Math.exp(a-m)/(Math.exp(a-m)+Math.exp(b-m));
            }
        }
    }

    private void persist(Map<String,Object> job,long jobId,double score,boolean attention) {
        if(db.queryForList("SELECT id FROM psy_emotion_jobs WHERE id=? AND status='processing' FOR UPDATE",jobId).isEmpty()) return;
        String uid=Objects.toString(job.get("uid")), source=Objects.toString(job.get("source_type")), sourceId=Objects.toString(job.get("source_id"));
        String now=Instant.now().toString();
        KeyHolder key=new GeneratedKeyHolder();
        db.update(connection -> {
            PreparedStatement ps=connection.prepareStatement("INSERT INTO psy_emotion_events(uid,source_type,source_id,negative_score,attention,model_version,created_at) VALUES (?,?,?,?,?,?,?)",new String[]{"id"});
            ps.setString(1,uid); ps.setString(2,source); ps.setString(3,sourceId); ps.setDouble(4,score); ps.setBoolean(5,attention); ps.setString(6,MODEL_VERSION); ps.setString(7,now); return ps;
        },key);
        long eventId=Objects.requireNonNull(key.getKey()).longValue();
        if(attention) {
            Set<String> recipients=new LinkedHashSet<>(); recipients.add(uid);
            Set<String> admins=new HashSet<>();
            for(UserAccount user:users.findAll()) if(user.getType()==0) { recipients.add(user.getUid()); admins.add(user.getUid()); }
            if(admins.isEmpty()) db.update("UPDATE psy_emotion_events SET admin_delivery_pending=TRUE WHERE id=?",eventId);
            for(String recipient:recipients) {
                String message=recipient.equals(uid) && admins.contains(recipient) ? "你的文字触发了情绪关注提醒，你同时作为管理员收到该提醒。模型可能误判，请结合实际情况处理。" : recipient.equals(uid) ? "你的文字可能表达了较强的负面情绪。模型可能误判，如有需要请联系信任的人寻求支持。" : "用户 "+uid+" 的文字出现需要关注的情绪表达，请结合实际情况核实。";
                db.update("INSERT INTO psy_notifications(recipient_uid,event_id,target_uid,message,is_read,created_at) VALUES (?,?,?,?,?,?)",recipient,eventId,uid,message,false,now);
            }
        }
        db.update("UPDATE psy_emotion_jobs SET status='done',content=NULL WHERE id=?",jobId);
    }

    @PreDestroy
    void closeResources() {
        try { if(tokenizer!=null) tokenizer.close(); } catch(Exception ignored) {}
        try { if(session!=null) session.close(); } catch(Exception ignored) {}
        tokenizer=null; session=null;
    }
}
