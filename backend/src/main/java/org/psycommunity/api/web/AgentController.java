package org.psycommunity.api.web;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.annotation.PostConstruct;
import org.psycommunity.api.domain.UserAccount;
import org.psycommunity.api.service.ApiException;
import org.psycommunity.api.service.AuthService;
import org.psycommunity.api.service.EmotionService;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.web.bind.annotation.*;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.time.Instant;
import java.sql.PreparedStatement;
import java.util.*;

@RestController
@RequestMapping("/api/agent")
public class AgentController {
    private final JdbcTemplate db;
    private final AuthService auth;
    private final ObjectMapper mapper;
    private final EmotionService emotion;
    private final String apiUrl, apiKey, model;
    private final HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(10)).build();

    public AgentController(JdbcTemplate db, AuthService auth, ObjectMapper mapper, EmotionService emotion,
                           @Value("${app.agent.api-url:}") String apiUrl,
                           @Value("${app.agent.api-key:}") String apiKey,
                           @Value("${app.agent.model:}") String model) {
        this.db=db; this.auth=auth; this.mapper=mapper; this.emotion=emotion;
        this.apiUrl=apiUrl.trim(); this.apiKey=apiKey.trim(); this.model=model.trim();
    }

    @PostConstruct
    void createTable() {
        db.execute("CREATE TABLE IF NOT EXISTS psy_agent_messages (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid VARCHAR(50) NOT NULL, role VARCHAR(16) NOT NULL, content VARCHAR(8000) NOT NULL, created_at VARCHAR(40) NOT NULL)");
    }

    @GetMapping("/status")
    public Map<String,Object> status(@RequestHeader(value="Authorization", required=false) String authorization) {
        auth.require(authorization);
        return Map.of("success", true, "configured", configured());
    }

    @GetMapping("/messages")
    public Map<String,Object> messages(@RequestHeader(value="Authorization", required=false) String authorization) {
        String uid=auth.require(authorization).getUid();
        List<Map<String,Object>> rows=new ArrayList<>(db.queryForList("SELECT id,role,content,created_at FROM psy_agent_messages WHERE uid=? ORDER BY id DESC LIMIT 100",uid));
        Collections.reverse(rows);
        return Map.of("success",true,"messages",rows);
    }

    @PostMapping("/messages")
    public Map<String,Object> send(@RequestHeader(value="Authorization", required=false) String authorization,
                                   @RequestBody Map<String,Object> input) {
        UserAccount user=auth.require(authorization);
        String content=Objects.toString(input.get("content"), "").trim();
        if(content.isBlank() || content.length()>4000) throw new ApiException(HttpStatus.BAD_REQUEST,"消息不能为空且不能超过4000字");
        if(!configured()) throw new ApiException(HttpStatus.SERVICE_UNAVAILABLE,"对话服务尚未配置，请联系管理员");
        KeyHolder key=new GeneratedKeyHolder();
        db.update(connection -> {
            PreparedStatement ps=connection.prepareStatement("INSERT INTO psy_agent_messages(uid,role,content,created_at) VALUES (?,?,?,?)",new String[]{"id"});
            ps.setString(1,user.getUid()); ps.setString(2,"user"); ps.setString(3,content); ps.setString(4,Instant.now().toString()); return ps;
        },key);
        emotion.submit(user.getUid(),"agent",Objects.requireNonNull(key.getKey()).longValue(),content);
        try {
            List<Map<String,Object>> history=new ArrayList<>(db.queryForList("SELECT role,content FROM psy_agent_messages WHERE uid=? ORDER BY id DESC LIMIT 12",user.getUid()));
            Collections.reverse(history);
            List<Map<String,String>> messages=new ArrayList<>();
            messages.add(Map.of("role","system","content","你是心理互助社区的支持性对话助手。请温和、简洁地倾听，避免诊断或承诺保密；遇到可能存在即时危险的表达，鼓励用户尽快联系身边可信任的人和当地紧急服务。"));
            for(Map<String,Object> row:history) messages.add(Map.of("role",String.valueOf(row.get("role")),"content",String.valueOf(row.get("content"))));
            String payload=mapper.writeValueAsString(Map.of("model",model,"messages",messages,"stream",false));
            HttpRequest request=HttpRequest.newBuilder(URI.create(apiUrl)).timeout(Duration.ofSeconds(60))
                    .header("Content-Type","application/json").header("Authorization","Bearer "+apiKey)
                    .POST(HttpRequest.BodyPublishers.ofString(payload)).build();
            HttpResponse<String> response=http.send(request,HttpResponse.BodyHandlers.ofString());
            if(response.statusCode()<200 || response.statusCode()>=300) throw new IllegalStateException("provider error");
            JsonNode result=mapper.readTree(response.body()).path("choices").path(0).path("message").path("content");
            if(!result.isTextual() || result.asText().isBlank()) throw new IllegalStateException("empty response");
            String reply=result.asText();
            if(reply.length()>8000) reply=reply.substring(0,8000);
            db.update("INSERT INTO psy_agent_messages(uid,role,content,created_at) VALUES (?,?,?,?)",user.getUid(),"assistant",reply,Instant.now().toString());
            return Map.of("success",true,"reply",reply);
        } catch (InterruptedException ex) {
            Thread.currentThread().interrupt();
            throw new ApiException(HttpStatus.SERVICE_UNAVAILABLE,"对话服务暂时不可用，请稍后重试");
        } catch (Exception ex) {
            throw new ApiException(HttpStatus.BAD_GATEWAY,"对话服务暂时不可用，请检查服务配置后重试");
        }
    }

    @DeleteMapping("/messages")
    public Map<String,Object> clear(@RequestHeader(value="Authorization", required=false) String authorization) {
        String uid=auth.require(authorization).getUid();
        db.update("DELETE FROM psy_agent_messages WHERE uid=?",uid);
        db.update("DELETE FROM psy_emotion_jobs WHERE uid=? AND source_type='agent' AND status<>'done'",uid);
        return Map.of("success",true);
    }

    private boolean configured() { return !apiUrl.isBlank() && !apiKey.isBlank() && !model.isBlank(); }
}
