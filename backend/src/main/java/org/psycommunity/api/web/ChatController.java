    @PutMapping("/chat/group/{gid}/info")
    public Map<String,Object> updateGroup(@RequestHeader(value="Authorization",required=false) String token,@PathVariable long gid,@RequestBody Map<String,Object> input) {
        UserAccount user=auth.require(token); Map<String,Object> old=findGroup(gid);
        if(!str(old.get("owner_uid")).equals(user.getUid()) && user.getType()!=0) throw forbidden();
        String name=input.containsKey("name")?str(input.get("name")):str(old.get("name"));
        String avatar=input.containsKey("avatar")?str(input.get("avatar")):str(old.get("avatar"));
        String announcement=input.containsKey("announcement")?str(input.get("announcement")):str(old.get("announcement"));
        if(name.isBlank()||name.length()>100) throw bad("请输入群名称");
        if(announcement.length()>1000) throw bad("群公告过长");
        db.update("UPDATE psy_groups SET name=?,avatar=?,announcement=? WHERE id=?",name,avatar,announcement,gid); return body("success",true,"group_info",group(findGroup(gid)));
    }

