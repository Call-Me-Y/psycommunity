    @PostMapping({"/chat/private/send", "/chat/admin/send", "/chat/group/send"})
    public Map<String,Object> send(@RequestHeader(value="Authorization",required=false) String token,@RequestBody Map<String,Object> input,jakarta.servlet.http.HttpServletRequest request) {
        UserAccount user=auth.require(token); boolean isGroup=request.getRequestURI().contains("/group/");
        Long gid=isGroup?longValue(input.get("gid")):null;
        String receiver=isGroup?null:str(input.get("receiver_uid"));
        if(isGroup) member(gid,user.getUid());
        else if(!users.existsById(receiver)) throw missing("接收用户不存在");
        String content=str(input.get("content")); if(content.isBlank()||content.length()>4000) throw bad("消息内容不能为空或过长");
        int msgType=(int)longValue(input.getOrDefault("msg_type",0));
        long id=insert("INSERT INTO psy_messages(sender_uid,receiver_uid,gid,content,msg_type,link,sent_time) VALUES (?,?,?,?,?,?,?)",user.getUid(),receiver,gid,content,msgType,str(input.get("link")),Instant.now().toString());
        if(msgType==0) emotion.submit(user.getUid(),"chat",id,content);
        return body("success",true,"id",id,"message_id",id);
    }

    @GetMapping("/chat/private/messages")
    public Map<String,Object> privateMessages(@RequestHeader(value="Authorization",required=false) String token,@RequestParam String other_uid,@RequestParam(defaultValue="50") int limit,@RequestParam(defaultValue="0") int offset) {
        String uid=auth.require(token).getUid();
        List<Map<String,Object>> rows=db.queryForList("SELECT * FROM psy_messages WHERE gid IS NULL AND ((sender_uid=? AND receiver_uid=?) OR (sender_uid=? AND receiver_uid=?)) ORDER BY id DESC LIMIT ? OFFSET ?",uid,other_uid,other_uid,uid,clamp(limit),Math.max(0,offset));
        return body("success",true,"messages",rows.stream().map(this::message).toList());
    }

