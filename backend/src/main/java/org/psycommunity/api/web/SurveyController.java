import java.sql.PreparedStatement;
import java.time.Instant;
import java.util.*;

@RestController
@RequestMapping("/api/surveys")
public class SurveyController {
    private final JdbcTemplate db;
    private final AuthService auth;
    private final ObjectMapper json;
    private final UserProfileRepository profiles;

    public SurveyController(JdbcTemplate db, AuthService auth, ObjectMapper json, UserProfileRepository profiles) {
        this.db = db; this.auth = auth; this.json = json; this.profiles = profiles;
    }

    @PostConstruct
    void createTables() {
        db.execute("CREATE TABLE IF NOT EXISTS psy_surveys (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_uid VARCHAR(50) NOT NULL, payload VARCHAR(64000) NOT NULL)");
        db.execute("ALTER TABLE psy_surveys ADD COLUMN IF NOT EXISTS created_time VARCHAR(40)");
        db.execute("CREATE TABLE IF NOT EXISTS psy_survey_answers (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, survey_id BIGINT NOT NULL, uid VARCHAR(50) NOT NULL, payload VARCHAR(64000) NOT NULL, scores VARCHAR(16000) NOT NULL, created_at VARCHAR(40) NOT NULL)");
    }

    @GetMapping
    public Map<String,Object> list(@RequestHeader(value="Authorization", required=false) String authorization) {
        auth.require(authorization);
        return Map.of("success", true, "surveys", db.queryForList("SELECT * FROM psy_surveys ORDER BY id DESC").stream().map(this::survey).toList());
    }

    @GetMapping("/{sid}")
    public Map<String,Object> get(@RequestHeader(value="Authorization", required=false) String authorization, @PathVariable long sid) {
        auth.require(authorization);
        return Map.of("success", true, "survey", survey(find(sid)));
    }

    @PostMapping
    @Transactional
    public Map<String,Object> create(@RequestHeader(value="Authorization", required=false) String authorization, @RequestBody Map<String,Object> data) {
        UserAccount user = auth.require(authorization);
        if (user.getType() != 0) throw forbidden();
        if (str(data.get("name")).isBlank() || !(data.get("questions") instanceof List<?> questions) || questions.isEmpty()) throw bad("请填写测评名称和问题");
        if (str(data.get("cover")).isBlank() || str(data.get("cover")).equalsIgnoreCase("null")) data.put("cover", "/static/cover.jpg");
        int n = 0;
        for (Object item : questions) {
            if (!(item instanceof Map<?,?>)) throw bad("问题格式不正确");
            @SuppressWarnings("unchecked") Map<String,Object> q = (Map<String,Object>) item;
            q.put("qid", ++n);
            if (q.get("options") instanceof List<?> options) {
                int i = 0;
                for (Object option : options) if (option instanceof Map<?,?>) {
                    @SuppressWarnings("unchecked") Map<String,Object> o = (Map<String,Object>) option;
                    o.put("oid", ++i);
                }
            }
        }
        long id = insert("INSERT INTO psy_surveys(owner_uid,payload,created_time) VALUES (?,?,?)", user.getUid(), encode(data), Instant.now().toString());
        return Map.of("success", true, "sid", id, "message", "测评已创建");
    }

    @PostMapping("/{sid}/submit")
    @Transactional
    public Map<String,Object> submit(@RequestHeader(value="Authorization", required=false) String authorization,
                                     @PathVariable long sid, @RequestBody Map<String,Object> input) {
        UserAccount user = auth.require(authorization);
        Map<String,Object> survey = survey(find(sid));
        Map<String,Object> answers = input.get("answers") instanceof Map<?,?> map ? cast(map) : Map.of();
        List<?> questions = list(survey.get("questions"));
        double[] values = new double[questions.size()];
        for (int i=0; i<questions.size(); i++) {
            Map<String,Object> q = cast((Map<?,?>) questions.get(i));
            Object answer = answers.get(str(q.get("qid")));
            int type = number(q.get("type")).intValue();
            if (type != 4 && (answer == null || answer instanceof List<?> a && a.isEmpty())) throw bad("请完成所有必填问题");
            if (type == 4) continue;
            if (type < 0 || type > 3) throw bad("问题类型不正确");
            List<?> selected = type == 3 && answer instanceof List<?> a ? a : List.of(answer);
            if (type != 3 && answer instanceof List<?> || type == 3 && !(answer instanceof List<?>)) throw bad("答案格式不正确");
            List<Double> allowed = new ArrayList<>();
            if (type == 2 || type == 3) for (Object option : list(q.get("options"))) {
                if (option instanceof Map<?,?> item) allowed.add(strictNumber(item.get("value")));
            }
            for (Object item : selected) {
                double value = strictNumber(item);
                if (type == 0 && (value < -5 || value > 5 || value != Math.rint(value))
                        || type == 1 && value != 0 && value != 1
                        || (type == 2 || type == 3) && !allowed.contains(value)) throw bad("答案超出可选范围");
                values[i] += value;
            }
        }
        for (Object text : list(input.get("textInputAnswers"))) if (text != null && str(text).length() > 100) throw bad("文字回答不能超过100字");
        List<Map<String,Object>> scores = new ArrayList<>();
        for (Object item : list(survey.get("results"))) {
            Map<String,Object> result = cast((Map<?,?>) item);
            double value;
            try { value = new Formula(str(result.get("expression")), values).evaluate(); }
            catch (RuntimeException ex) { throw bad("测评结果公式无法计算，请联系创建者检查公式"); }
            scores.add(Map.of("name", str(result.get("name")), "value", value));
        }
        insert("INSERT INTO psy_survey_answers(survey_id,uid,payload,scores,created_at) VALUES (?,?,?,?,?)", sid, user.getUid(), encode(input), encode(scores), Instant.now().toString());
        return Map.of("success", true, "results", scores);
    }

    @DeleteMapping("/{sid}")
    @Transactional
    public Map<String,Object> delete(@RequestHeader(value="Authorization", required=false) String authorization, @PathVariable long sid) {
        UserAccount user = auth.require(authorization);
        if (user.getType() != 0) throw forbidden();
        find(sid);
        db.update("DELETE FROM psy_survey_answers WHERE survey_id=?", sid);
        db.update("DELETE FROM psy_surveys WHERE id=?", sid);
        return Map.of("success", true, "message", "测评已删除");
    }

    @GetMapping({"/results/user", "/results/user/{uid}", "/results/all"})
    public Map<String,Object> results(@RequestHeader(value="Authorization", required=false) String authorization,
                                      @PathVariable(required=false) String uid, jakarta.servlet.http.HttpServletRequest request) {
        UserAccount current = auth.require(authorization);
        boolean all = request.getRequestURI().endsWith("/all");
        String target = uid == null ? current.getUid() : uid;
        if ((all || !target.equals(current.getUid())) && current.getType() != 0) throw forbidden();
        List<Map<String,Object>> rows = all ? db.queryForList("SELECT * FROM psy_survey_answers ORDER BY id DESC") : db.queryForList("SELECT * FROM psy_survey_answers WHERE uid=? ORDER BY id DESC", target);
        List<Map<String,Object>> result = new ArrayList<>();
        for (Map<String,Object> row : rows) {
            Map<String,Object> s = survey(find(((Number)row.get("survey_id")).longValue()));
            String who = str(row.get("uid"));
            Map<String,Object> payload = decode(str(row.get("payload")));
            result.add(body("uid", who, "userName", profiles.findById(who).map(p -> p.getName()).orElse(who), "sid", s.get("sid"), "surveyName", s.get("name"), "doneTime", row.get("created_at"), "scores", decodeList(str(row.get("scores"))), "textInputs", String.join("; ", list(payload.get("textInputAnswers")).stream().filter(Objects::nonNull).map(Object::toString).toList())));
        }
        return Map.of("success", true, "results", result);
    }

    @GetMapping({"/answers/details", "/answers/details/{uid}"})
    public Map<String,Object> details(@RequestHeader(value="Authorization", required=false) String authorization, @PathVariable(required=false) String uid) {
        UserAccount current = auth.require(authorization);
        boolean all = "all".equals(uid);
        String target = uid == null ? current.getUid() : uid;
        if ((all || !target.equals(current.getUid())) && current.getType() != 0) throw forbidden();
        List<Map<String,Object>> rows = all ? db.queryForList("SELECT * FROM psy_survey_answers ORDER BY id DESC") : db.queryForList("SELECT * FROM psy_survey_answers WHERE uid=? ORDER BY id DESC", target);
        Map<Long,Map<String,Object>> grouped = new LinkedHashMap<>();
        for (Map<String,Object> row : rows) {
            long sid = ((Number)row.get("survey_id")).longValue();
            Map<String,Object> s = survey(find(sid));
            Map<String,Object> payload = decode(str(row.get("payload")));
            Map<String,Object> answers = payload.get("answers") instanceof Map<?,?> m ? cast(m) : Map.of();
            List<?> textIds = list(payload.get("textInputQids")), textValues = list(payload.get("textInputAnswers"));
            @SuppressWarnings("unchecked") List<Map<String,Object>> items = (List<Map<String,Object>>) grouped.computeIfAbsent(sid, k -> body("sid", sid, "surveyName", s.get("name"), "answers", new ArrayList<Map<String,Object>>())).get("answers");
            int order = 0;
            for (Object qObj : list(s.get("questions"))) {
                Map<String,Object> q = cast((Map<?,?>)qObj);
                int type = number(q.get("type")).intValue();
                Object value = answers.get(str(q.get("qid")));
                if (type == 4) { int index = textIds.indexOf(q.get("qid")); value = index >= 0 && index < textValues.size() ? textValues.get(index) : null; }
                String who = str(row.get("uid"));
                items.add(body("uid", who, "userName", profiles.findById(who).map(p -> p.getName()).orElse(who), "orderNum", ++order, "questionContent", q.get("content"), "answerType", type, "answer", value == null ? "" : value instanceof List<?> ? encode(value) : str(value), "doneTime", row.get("created_at")));
            }
        }
        return Map.of("success", true, "data", grouped.values());
    }

    private Map<String,Object> find(long id) { return db.queryForList("SELECT * FROM psy_surveys WHERE id=?", id).stream().findFirst().orElseThrow(() -> new ApiException(HttpStatus.NOT_FOUND,"测评不存在")); }
    private Map<String,Object> survey(Map<String,Object> row) { Map<String,Object> result = decode(str(row.get("payload"))); if (str(result.get("cover")).isBlank() || str(result.get("cover")).equalsIgnoreCase("null")) result.put("cover", "/static/cover.jpg"); result.put("sid", ((Number)row.get("id")).longValue()); result.put("created_time", str(row.get("created_time"))); return result; }
    private long insert(String sql, Object... args) { KeyHolder key = new GeneratedKeyHolder(); db.update(c -> { PreparedStatement ps = c.prepareStatement(sql, new String[]{"id"}); for (int i=0;i<args.length;i++) ps.setObject(i+1,args[i]); return ps; }, key); return Objects.requireNonNull(key.getKey()).longValue(); }
    private String encode(Object value) { try { return json.writeValueAsString(value); } catch (Exception ex) { throw bad("数据格式不正确"); } }
    private Map<String,Object> decode(String value) { try { return json.readValue(value, new TypeReference<>(){}); } catch (Exception ex) { throw bad("数据格式不正确"); } }
    private List<?> decodeList(String value) { try { return json.readValue(value, new TypeReference<List<Object>>(){}); } catch (Exception ex) { throw bad("数据格式不正确"); } }
    private static String str(Object value) { return value == null ? "" : value.toString(); }
    private static Number number(Object value) { try { return Double.valueOf(str(value)); } catch (Exception ex) { return 0; } }
    private static double strictNumber(Object value) { try { double n=Double.parseDouble(str(value)); if (!Double.isFinite(n)) throw new NumberFormatException(); return n; } catch (Exception ex) { throw bad("答案必须是有效数字"); } }
    private static List<?> list(Object value) { return value instanceof List<?> l ? l : List.of(); }
    @SuppressWarnings("unchecked") private static Map<String,Object> cast(Map<?,?> value) { return (Map<String,Object>)value; }
    private static ApiException bad(String message) { return new ApiException(HttpStatus.BAD_REQUEST, message); }
    private static ApiException forbidden() { return new ApiException(HttpStatus.FORBIDDEN, "没有权限执行此操作"); }
    private static Map<String,Object> body(Object... values) { Map<String,Object> result=new LinkedHashMap<>(); for(int i=0;i<values.length;i+=2) result.put(values[i].toString(),values[i+1]); return result; }

    // A small arithmetic parser: expressions never execute as code.
    private static final class Formula {
        private final String s; private final double[] values; private int p;
        Formula(String s, double[] values) { this.s=s.replaceAll("\\s+", ""); this.values=values; }
        double evaluate() { double v=expression(); if(p!=s.length() || !Double.isFinite(v)) throw new IllegalArgumentException(); return v; }
        double expression() { double v=term(); while(p<s.length() && (s.charAt(p)=='+' || s.charAt(p)=='-')) { char op=s.charAt(p++); double x=term(); v=op=='+'?v+x:v-x; } return v; }
        double term() { double v=factor(); while(p<s.length() && (s.charAt(p)=='*' || s.charAt(p)=='/')) { char op=s.charAt(p++); double x=factor(); v=op=='*'?v*x:v/x; } return v; }
        double factor() { if(p>=s.length()) throw new IllegalArgumentException(); char c=s.charAt(p); if(c=='-') {p++; return -factor();} if(c=='+') {p++; return factor();} if(c=='(') {p++; double v=expression(); if(p>=s.length()||s.charAt(p++)!=')') throw new IllegalArgumentException(); return v;} if(c=='Q') {p++; int start=p; while(p<s.length()&&Character.isDigit(s.charAt(p)))p++; int i=Integer.parseInt(s.substring(start,p))-1; if(i<0||i>=values.length)throw new IllegalArgumentException(); return values[i];} int start=p; while(p<s.length()&&(Character.isDigit(s.charAt(p))||s.charAt(p)=='.'))p++; return Double.parseDouble(s.substring(start,p)); }
    }
}
